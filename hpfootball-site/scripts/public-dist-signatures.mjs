import {readdir,readFile,stat} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve(process.argv[2]||'dist');
const assets=path.join(root,'client');
const server=path.join(root,'server');
const signatures=/\b(?:chatgpt|openai|claude(?:[ -]?code)?|jules|antigravity|opencode|copilot|generated by ai|ai-generated)\b/i;
const extensions=new Set(['.html','.js','.mjs','.css','.svg','.json','.txt','.xml','.webmanifest']);
const violations=[];
const serverFindings=[];
let examined=0;
async function walk(dir,mode='public'){
 for(const ent of await readdir(dir,{withFileTypes:true})){
  const p=path.join(dir,ent.name);
  if(ent.isDirectory()){await walk(p,mode);continue;}
  if(!ent.isFile()||!extensions.has(path.extname(ent.name)))continue;
  const st=await stat(p);
  if(st.size>5_000_000)continue;
  const data=await readFile(p,'utf8');
  const found=data.match(signatures);
  examined++;
  if(found){
   const hit={file:path.relative(root,p),signature:found[0]};
   if(mode==='public')violations.push(hit);
   else serverFindings.push(hit);
  }
 }
}
try{await walk(assets)}
catch(e){if(e.code==='ENOENT')throw Error('Missing dist/client: build output not available');throw e}
try{await walk(server,'server')}catch(e){if(e.code!=='ENOENT')throw e}
console.log(JSON.stringify({scanned:examined,publicViolations:violations,serverReviewFindings:serverFindings},null,2));
assert.equal(violations.length,0,'Public build contains agent strings');
