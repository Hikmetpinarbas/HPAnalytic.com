import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/pages/mac/lille-galatasaray-2026-10-21.astro', import.meta.url), 'utf8');

test('spatial matchup keeps three denominators and separate source matches', () => {
  assert.match(src, /Baskının miktarı değil, kazanımın yeri/);
  assert.equal((src.match(/class="hp-mechanism__item"/g) ?? []).length, 3);
  for (const pair of ['14 \/ 26', '11 \/ 19', '1 \/ 8']) assert.match(src, new RegExp(pair));
  assert.match(src, /Arsenal karşısında/);
  assert.match(src, /Barcelona karşısında/);
  assert.match(src, /rakip gücüne göre düzeltilmiş pres başarısı/);
});

test('momentum is described as an event-count proxy and not as possession or pressing', () => {
  assert.match(src, /Son üçte birde kim daha fazla aksiyon yaptı\?/);
  assert.match(src, /pres şiddetini, topa sahip olma oranını veya gol beklentisini doğrudan ölçmez/);
  assert.match(src, /ham olay farkı bazı dilimlerde pozitif/);
});

test('matchup is accessible and does not add pass-direction claims', () => {
  assert.equal((src.match(/class="hp-mechanism__track"/g) ?? []).length, 3);
  assert.match(src, /aria-labelledby="match-mechanism-title"/);
  assert.match(src, /@media\(max-width:820px\)/);
  assert.doesNotMatch(src, /AI-generated|generated by ChatGPT|generated by Claude/i);
});
